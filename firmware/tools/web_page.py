#!/usr/bin/env python3
# Builds src/web_page.h, the setup page web.cpp serves, from web/index.html:
# drops comments and indentation, gzips it, and writes it as a byte array.
# Run from the firmware folder after editing the page: python3 tools/web_page.py
import gzip
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "src", "web_page.h")

html = open(src, encoding="utf-8").read()
html = re.sub(r"<!--.*?-->\n?", "", html, flags=re.S)
html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
raw = html.encode("utf-8")
gz = gzip.compress(raw, compresslevel=9, mtime=0)

rows = [", ".join("0x%02x" % b for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
with open(dst, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/web_page.py from web/index.html. Do not edit by hand.\n")
    f.write("// %d bytes of HTML, %d gzipped.\n" % (len(raw), len(gz)))
    f.write("#pragma once\n\n#include <Arduino.h>\n\n")
    f.write("const uint8_t kWebPage[] PROGMEM = {\n    %s};\n" % ",\n    ".join(rows))
    f.write("constexpr size_t kWebPageSize = sizeof(kWebPage);\n")
print("web_page.h: %d bytes of HTML, %d gzipped" % (len(raw), len(gz)))
